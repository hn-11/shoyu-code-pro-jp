#!/usr/bin/env python3
"""Sumi Moji (variable): the same recipe scripts/build_latin.py uses for
the static faces — Source Code Pro VF as the base, Monaspace VF for the
punctuation/ligatures/one-cell arrows — but assembled as a CFF2 variable
font instead of twelve static instances. Two files come out, mirroring
Source Code Pro's own Upright/Italic split:

  dist/latin/SumiMoji[wght].otf         wght 200-900 (usWeightClass terms)
  dist/latin/SumiMoji-Italic[wght].otf  from SCP_VF_I, Monaspace slnt +
                                        the residual shear mona_transform
                                        already applies for the static
                                        Italic faces

Masters sit at the SCP VF's own master locations, read back from the CFF2
VarStore (build_latin.confirm_scp_master_wghts) — not assumed — plus the
Regular and Heavy positions (see the axis paragraph below). Monaspace
is bar-matched per master with erosion DISABLED (VFSource.matched
erode=False): erosion is a pathops boolean op on a fixed outline, not an
interpolatable deformation, so a VF master can't take that path (see
docs/sumi-moji-plan.md 段階2) — below SCP wght ≈366 Monaspace's punctuation
just stays at its own wght-200 floor instead, slightly heavier than the
bar-matched ideal. draw_clean's pathops.simplify pass is also disabled for
the same reason (overlap removal is not guaranteed point-compatible across
weights); masters keep overlapping contours, same as Adobe ships SCP's own
VF. No hinting, no subroutinizing: CFF2 VFs don't carry per-master hints
through fontTools's instancer, so static releases re-hint after
instancing (see build_latin.py), not here.

The wght axis is in usWeightClass terms, like the static faces' STAT:
user 300/350/400/500/700/900 = Light/Normal/Regular/Medium/Bold/Heavy,
default 400 = Regular (so OS/2 usWeightClass 400 matches the fvar
default, CSS `font-weight: 700` lands on OUR Bold, and a VF picked
without an axis value renders Regular, not the thinnest master). Each of
those user values maps (avar, generated by varLib from the designspace
axis map) to the SCP wght whose own '=' bar equals that Source Han Code
JP face's bar scaled 600/667 — the exact pairing build_latin.py's static
faces use, recomputed here as plain numbers instead of an instanced
font. The DESIGN coordinate the masters live on is SCP's own wght made
linear (scp_design_axis: its user wght pushed through SCP's fvar
normalization + avar, then stretched back onto 200..900), so that
straight-line interpolation between our masters reproduces SCP's
interpolation exactly — SCP's VF is NOT linear in its user wght (its
avar bends the axis, so e.g. user 300 sits only 27% of the way from the
200 master to the 400 master), and a VF that interpolated linearly in
SCP's user wght would put every intermediate weight in the wrong place
(the first cut of this script did: its Light was a 58u bar instead of
the static Light's 41u). The masters are SCP's own (read back from the
CFF2 VarStore, build_latin.confirm_scp_master_wghts) plus SCP instanced
at the Regular and Heavy positions — the Regular one is the default
master (a VF's default must be a master), the Heavy one is the axis
maximum (SCP's own 900 master sits above it, out of range; instancing
at Heavy is exact since SCP is linear between its 400 and 900 masters)
— and one at the Monaspace floor (mona_floor_wght: the SCP wght below
which Monaspace's bar-matching is clamped at its own wght 200), so the
clamped Monaspace outline is constant below it and tracks SCP above it.
STAT carries the same six user wght values as the static faces
(Regular elidable, linked to Bold) plus one 'ital' value per file (0
upright / 1 italic, upright linked to italic) — matching Source Code
Pro's own two-file STAT convention. MVAR/HVAR are excluded: nothing in
this recipe varies per-glyph metrics or advances by weight (advances are
fixed 600-multiples; OS/2 vertical metrics are measured once on the
default master and the same values are shared by every instance), so
there is no variation for either table to carry.

Usage:
  python scripts/build_latin_vf.py [upright|italic]   # default: both
Env (all required):
  SCP_VF_U, SCP_VF_I, MONA_VF, SHCJ_TTC   as for build_latin.py
Env (optional): SHOYU_VERSION
"""

